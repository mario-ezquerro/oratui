  /// High-contrast retro LCD progress bar with cyan border, bright fill bar, and inline % badge.
  Widget _lcdProgressBar({
    required double pct,
    required String label,
    bool invertColors = false,
    String? customBadgeText,
  }) {
    final safePct = pct.isNaN || pct.isInfinite ? 0.0 : pct.clamp(0.0, 100.0);
    final Color barColor;
    if (invertColors) {
      barColor = safePct > 50
          ? const Color(0xFF00FF66)
          : (safePct > 20 ? const Color(0xFFFFB300) : const Color(0xFFFF3344));
    } else {
      barColor = safePct >= 90
          ? const Color(0xFFFF3344)
          : (safePct >= 75 ? const Color(0xFFFFB300) : const Color(0xFF00FF66));
    }

    final badge = customBadgeText ?? '${safePct.toStringAsFixed(1)}%';

    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Container(
          height: 20,
          decoration: BoxDecoration(
            color: const Color(0xFF001A4D),
            border: Border.all(color: const Color(0xFF5FFFFF), width: 1.2),
            borderRadius: BorderRadius.circular(2),
          ),
          child: Stack(
            children: [
              FractionallySizedBox(
                widthFactor: (safePct / 100.0).clamp(0.02, 1.0),
                heightFactor: 1.0,
                child: Container(
                  decoration: BoxDecoration(
                    gradient: LinearGradient(
                      colors: [
                        barColor.withValues(alpha: 0.85),
                        barColor,
                      ],
                    ),
                  ),
                ),
              ),
              Center(
                child: Text(
                  badge,
                  style: const TextStyle(
                    color: Colors.white,
                    fontWeight: FontWeight.bold,
                    fontSize: 11,
                    shadows: [
                      Shadow(color: Colors.black, offset: Offset(1, 1), blurRadius: 2),
                    ],
                  ),
                ),
              ),
            ],
          ),
        ),
        if (label.isNotEmpty) ...[
          const SizedBox(height: 3),
          Text(label, style: const TextStyle(color: Colors.white, fontSize: 11)),
        ],
      ],
    );
  }

