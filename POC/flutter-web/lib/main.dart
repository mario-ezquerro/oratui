  Future<void> _loadAuthAndServers() async {
    try {
      final authResp =
          await http.get(Uri.parse('auth-config.json')).timeout(const Duration(seconds: 2));
      if (authResp.statusCode == 200) {
        final authMap = jsonDecode(authResp.body) as Map<String, dynamic>;
        _expectedUser = (authMap['username'] ?? 'admin').toString();
        _expectedPass = (authMap['password'] ?? 'admin').toString();
        _configuredApiToken = (authMap['api_token'] ?? '').toString();
        _loginTokenCtrl.text = _configuredApiToken;
      }
    } catch (_) {
      // Keep default admin / admin
    }

    try {
      final resp = await http.get(Uri.parse('servers.json')).timeout(const Duration(seconds: 2));
      if (resp.statusCode == 200) {
        final decoded = jsonDecode(resp.body) as Map<String, dynamic>;
        final rawList = (decoded['servers'] as List?) ?? [];
        if (rawList.isNotEmpty) {
          final parsed = rawList
              .map((e) => ServerEndpoint.fromJson(Map<String, dynamic>.from(e as Map)))
              .toList();
          setState(() {
            _servers = parsed;
            _selectedServer = _servers.first;
          });
        }
      }
    } catch (_) {
      // Keep default server list
    }

    await _fetchTelemetry();
  }

  void _handleLoginSubmit() {
    final u = _loginUserCtrl.text.trim();
    final p = _loginPassCtrl.text;
    final tok = _loginTokenCtrl.text.trim();

    if (u == _expectedUser && p == _expectedPass) {
      final b64 = base64Encode(utf8.encode('$u:$p'));
      setState(() {
        _isAuthenticated = true;
        _loggedInUser = u;
        _sessionBasicAuthHeader = 'Basic $b64';
        if (tok.isNotEmpty) {
          _configuredApiToken = tok;
        }
        _loginError = null;
      });
      _fetchTelemetry();
    } else {
      setState(() {
        _loginError = 'Usuario o contraseña incorrectos (Definidos en .env: FLUTTER_WEB_USER / FLUTTER_WEB_PASSWORD).';
      });
    }
  }

  Map<String, String> _buildAuthHeaders() {
    final headers = <String, String>{
      'Content-Type': 'application/json',
    };
    if (_sessionBasicAuthHeader.isNotEmpty) {
      headers['Authorization'] = _sessionBasicAuthHeader;
    }
    if (_configuredApiToken.isNotEmpty) {
      headers['X-OraTui-Token'] = _configuredApiToken;
    }
    return headers;
  }

  Future<void> _fetchTelemetry() async {
    try {
      final baseUrl = _selectedServer.url.replaceAll(RegExp(r'/$'), '');
      final results = await Future.wait([
        http
            .get(Uri.parse('$baseUrl/api/v1/state'), headers: _buildAuthHeaders())
            .timeout(const Duration(seconds: 4)),
        http
            .get(Uri.parse('$baseUrl/api/v1/sre'), headers: _buildAuthHeaders())
            .timeout(const Duration(seconds: 4)),
      ]);

      if (results[0].statusCode == 200 && results[1].statusCode == 200) {
        final stMap = jsonDecode(results[0].body) as Map<String, dynamic>;
        final sreMap = jsonDecode(results[1].body) as Map<String, dynamic>;
        setState(() {
          _stateData = (stMap['state'] as Map<String, dynamic>?) ?? stMap;
          _sreData = sreMap;
          _lastError = null;
          _lastRefresh = DateTime.now();
          _loading = false;
          _syncSreControllersIfNeeded(sreMap['config'] as Map<String, dynamic>?);
        });
        return;
      }
      throw Exception('HTTP ${results[0].statusCode} / ${results[1].statusCode}');
    } catch (e) {
      setState(() {
        _lastError =
            'Sin conexión directa a ${_selectedServer.url} ($e). Mostrando datos de demostración interactivos.';
        _stateData = _buildMockState();
        _sreData = _buildMockSre();
        _syncSreControllersIfNeeded(_sreData['config'] as Map<String, dynamic>?);
        _lastRefresh = DateTime.now();
        _loading = false;
      });
    }
  }

