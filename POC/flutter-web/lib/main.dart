        'duration_ms': 142,
        'executed_at': DateTime.now().toIso8601String(),
      };
    }

    if (!mounted) return;
    Navigator.pop(context);

    await showDialog(
      context: context,
      builder: (ctx) => _buildTerminalOutputModal(ctx, resultPayload),
    );
    _fetchTelemetry();
  }

